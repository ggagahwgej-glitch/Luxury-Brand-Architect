/**
 * Builds `supabase/apply-all.sql` — every migration plus the seed in the exact
 * order the SQL editor needs them, as one copy-paste file.
 *
 *   npm run sql:bundle
 *
 * The individual files remain the source of truth (that is what `supabase db
 * push` and `npm run verify:sql` use); this is a convenience artefact for
 * projects without the Supabase CLI.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const FILES = [
  "supabase/migrations/0001_initial_schema.sql",
  "supabase/migrations/0002_rls_policies.sql",
  "supabase/migrations/0003_storage.sql",
  "supabase/seed.sql",
];

const header = `-- ============================================================================
--  AURUM ESTATES · COMPLETE DATABASE SETUP
--  Generated by \`npm run sql:bundle\` — do not edit by hand.
--
--  Paste this whole file into the Supabase SQL editor of the client's project
--  and run it once. It is idempotent ("if not exists", "on conflict"), so
--  re-running it after an update is safe.
-- ============================================================================

`;

const body = FILES.map((file) => {
  const sql = readFileSync(path.join(root, file), "utf8").trimEnd();
  return `-- ────────────────────────────────────────────────────────────────────────────
--  ${file}
-- ────────────────────────────────────────────────────────────────────────────

${sql}
`;
}).join("\n");

const out = path.join(root, "supabase/apply-all.sql");
writeFileSync(out, header + body);
const lines = (header + body).split("\n").length;
console.log(`✓ supabase/apply-all.sql written (${lines} lines from ${FILES.length} files)`);
